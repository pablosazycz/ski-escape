let currentLanguage = (navigator.language && navigator.language.startsWith('es')) ? 'ES' : 'EN';
const savedLang = localStorage.getItem('ski_escape_lang');
if (savedLang && (savedLang === 'ES' || savedLang === 'EN')) {
  currentLanguage = savedLang;
}

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(lang) {
  if (lang === 'ES' || lang === 'EN') {
    currentLanguage = lang;
    localStorage.setItem('ski_escape_lang', lang);
    applyTranslations();
  }
}

export function toggleLanguage() {
  const nextLang = currentLanguage === 'ES' ? 'EN' : 'ES';
  setLanguage(nextLang);
  return nextLang;
}

export function t(key) {
  const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS.EN;
  return dict[key] || key;
}

export function applyTranslations() {
  const lang = currentLanguage;
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.EN;

  // 1. Botón de idioma
  const langBtn = document.getElementById('langBtn');
  if (langBtn) langBtn.innerText = dict.lang_btn;

  // 2. Subtítulo del Menú
  const sub = document.querySelector('.game-subtitle');
  if (sub) sub.innerText = dict.app_subtitle;

  // 3. Stats del Menú
  const statLabels = document.querySelectorAll('.stat-label');
  if (statLabels && statLabels.length >= 2) {
    statLabels[0].innerText = dict.highscore;
    statLabels[1].innerText = dict.coins;
  }

  // 4. Selectores del Menú
  const labels = document.querySelectorAll('.selector-label');
  if (labels && labels.length >= 4) {
    labels[0].innerText = dict.char_label;
    labels[1].innerText = dict.style_label;
    labels[2].innerText = dict.diff_label;
    labels[3].innerText = dict.yeti_label;
  }

  const charSkier = document.getElementById('charSkierBtn');
  if (charSkier) charSkier.innerText = dict.char_skier;
  const charBoarder = document.getElementById('charBoarderBtn');
  if (charBoarder) charBoarder.innerText = dict.char_boarder;

  const styleBanana = document.getElementById('styleBananaBtn');
  if (styleBanana) styleBanana.innerText = dict.style_banana;
  const styleHuman = document.getElementById('styleHumanBtn');
  if (styleHuman) styleHuman.innerText = dict.style_human;

  const diffEasy = document.getElementById('diffEasyBtn');
  if (diffEasy) diffEasy.innerText = dict.diff_easy;
  const diffMed = document.getElementById('diffMedBtn');
  if (diffMed) diffMed.innerText = dict.diff_med;
  const diffHard = document.getElementById('diffHardBtn');
  if (diffHard) diffHard.innerText = dict.diff_hard;

  // 5. Botones de acción principales
  const playBtnSpan = document.querySelector('#playBtn span');
  if (playBtnSpan) playBtnSpan.innerText = dict.play_btn;

  const shopBtnSpan = document.querySelector('#shopBtn span');
  if (shopBtnSpan) shopBtnSpan.innerText = dict.shop_btn;

  const questsBtnSpan = document.querySelector('#questsBtn span');
  if (questsBtnSpan) questsBtnSpan.innerText = dict.quests_btn;

  const howToBtnSpan = document.querySelector('#howToBtn span');
  if (howToBtnSpan) howToBtnSpan.innerText = dict.howto_btn;

  const privLink = document.querySelector('.privacy-link');
  if (privLink) privLink.innerText = dict.privacy_link;

  // 6. Tienda
  const shopTitle = document.querySelector('#shopModal .panel-title');
  if (shopTitle) shopTitle.innerText = dict.shop_title;

  const freeCoinsSpan = document.querySelector('#freeCoinsAdBtn span');
  if (freeCoinsSpan) freeCoinsSpan.innerText = dict.shop_reward_btn;

  const closeShopSpan = document.querySelector('#closeShopBtn span');
  if (closeShopSpan) closeShopSpan.innerText = dict.shop_back_btn;

  // Actualizar descripciones de skins en la tienda
  const skinCards = document.querySelectorAll('.skin-card');
  skinCards.forEach(card => {
    const skinKey = card.getAttribute('data-skin');
    const titleEl = card.querySelector('.skin-title');
    const descEl = card.querySelector('.skin-desc');
    if (skinKey === 'default') {
      if (titleEl) titleEl.innerText = dict.skin_classic_title;
      if (descEl) descEl.innerText = dict.skin_classic_desc;
    } else if (skinKey === 'fire') {
      if (titleEl) titleEl.innerText = dict.skin_fire_title;
      if (descEl) descEl.innerText = dict.skin_fire_desc;
    } else if (skinKey === 'cyber') {
      if (titleEl) titleEl.innerText = dict.skin_cyber_title;
      if (descEl) descEl.innerText = dict.skin_cyber_desc;
    } else if (skinKey === 'yeti_gold') {
      if (titleEl) titleEl.innerText = dict.skin_gold_title;
      if (descEl) descEl.innerText = dict.skin_gold_desc;
    } else if (skinKey === 'start_shield') {
      if (titleEl) titleEl.innerText = dict.skin_shield_title;
      if (descEl) descEl.innerText = dict.skin_shield_desc;
    } else if (skinKey === 'super_magnet') {
      if (titleEl) titleEl.innerText = dict.skin_magnet_title;
      if (descEl) descEl.innerText = dict.skin_magnet_desc;
    }
  });

  // 7. Misiones
  const questsTitle = document.querySelector('#questsModal .panel-title');
  if (questsTitle) questsTitle.innerText = dict.quests_title;
  const questsSub = document.querySelector('#questsModal .panel-subtitle');
  if (questsSub) questsSub.innerText = dict.quests_subtitle;
  const closeQuestsSpan = document.querySelector('#closeQuestsBtn span');
  if (closeQuestsSpan) closeQuestsSpan.innerText = dict.quests_back;

  // 8. Instrucciones
  const instTitle = document.querySelector('#instructionsPanel .panel-title');
  if (instTitle) instTitle.innerText = dict.howto_title;
  const instCloseSpan = document.querySelector('#closeInstBtn span');
  if (instCloseSpan) instCloseSpan.innerText = dict.howto_got_it;

  const stepTexts = document.querySelectorAll('.instruction-step .step-text');
  if (stepTexts && stepTexts.length >= 3) {
    stepTexts[0].innerHTML = `<strong>${dict.howto_step1_title}</strong><p>${dict.howto_step1_desc}</p>`;
    stepTexts[1].innerHTML = `<strong>${dict.howto_step2_title}</strong><p>${dict.howto_step2_desc}</p>`;
    stepTexts[2].innerHTML = `<strong>${dict.howto_step3_title}</strong><p>${dict.howto_step3_desc}</p>`;
  }

  // 9. Game Over & Pausa
  const restartBtnSpan = document.querySelector('#restartBtn span');
  if (restartBtnSpan) restartBtnSpan.innerText = dict.gameover_restart;
  const reviveBtnSpan = document.querySelector('#reviveBtn span:last-child');
  if (reviveBtnSpan) reviveBtnSpan.innerText = dict.gameover_revive;
  const mainBtnSpan = document.querySelector('#mainMenuBtn span');
  if (mainBtnSpan) mainBtnSpan.innerText = dict.gameover_menu;

  const pauseTitle = document.querySelector('#pauseMenu .panel-title');
  if (pauseTitle) pauseTitle.innerText = dict.pause_title;
  const resumeBtnSpan = document.querySelector('#resumeBtn span');
  if (resumeBtnSpan) resumeBtnSpan.innerText = dict.pause_resume;
  const pauseMuteSpan = document.querySelector('#pauseMuteBtn span');
  if (pauseMuteSpan) pauseMuteSpan.innerText = dict.pause_sound;
  const restartPauseSpan = document.querySelector('#restartPauseBtn span');
  if (restartPauseSpan) restartPauseSpan.innerText = dict.pause_restart;
  const mainPauseSpan = document.querySelector('#mainMenuPauseBtn span');
  if (mainPauseSpan) mainPauseSpan.innerText = dict.pause_menu;
}
